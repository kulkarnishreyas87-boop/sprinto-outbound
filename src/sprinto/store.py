"""Storage: page cache, Hunter cache, runs, decision records, feedback, LLM calls.

SQLite by default (CLI, tests). Postgres when DATABASE_URL is set (the live Vercel app): a small
adapter keeps the same `store.conn.execute(sql, params)` interface and rewrites the few
SQLite-only constructs, so every module works unchanged on both.
"""
from __future__ import annotations

import json
import os
import re
import sqlite3
import uuid
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Iterator

from .config import ROOT
from .models import DecisionRecord

DEFAULT_DB = ROOT / "data" / "pipeline.db"

# primary keys for INSERT OR REPLACE -> ON CONFLICT rewriting
_PK = {"pages": "url", "hunter_cache": "domain", "decision_records": "record_id", "run_items": "run_id, domain"}


def _to_postgres(sql: str) -> str:
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    m = re.match(r"\s*INSERT OR REPLACE INTO (\w+)\s*\(([^)]*)\)(.*)$", sql, re.S)
    if m:
        table, cols, rest = m.group(1), [c.strip() for c in m.group(2).split(",")], m.group(3)
        pk = [k.strip() for k in _PK[table].split(",")]
        updates = ", ".join(f"{c}=EXCLUDED.{c}" for c in cols if c not in pk)
        sql = f"INSERT INTO {table}({', '.join(cols)}){rest} ON CONFLICT ({', '.join(pk)}) DO UPDATE SET {updates}"
    return sql.replace("?", "%s")


class _PgConn:
    """Just enough of sqlite3.Connection for this codebase, on top of psycopg 3."""

    def __init__(self, url: str):
        import psycopg
        from psycopg.rows import dict_row

        # prepare_threshold=None: Neon's pooled URL runs PgBouncer in transaction mode, where
        # server-side prepared statements break between transactions.
        self._raw = psycopg.connect(url, autocommit=True, row_factory=dict_row, prepare_threshold=None)
        self._tx_stack: list = []      # nested `with conn:` blocks become savepoints

    def execute(self, sql: str, params: tuple | list = ()):
        return self._raw.execute(_to_postgres(sql), tuple(params))

    def executemany(self, sql: str, seq):
        with self._raw.cursor() as cur:
            cur.executemany(_to_postgres(sql), [tuple(p) for p in seq])
            return cur

    def executescript(self, script: str) -> None:
        stmts = [s.strip() for s in re.sub(r"--[^\n]*", "", script).split(";") if s.strip()]
        with self._raw.transaction():
            for s in stmts:
                self._raw.execute(_to_postgres(s))

    def commit(self) -> None:          # autocommit outside explicit transactions
        pass

    def __enter__(self):
        tx = self._raw.transaction()
        tx.__enter__()
        self._tx_stack.append(tx)
        return self

    def __exit__(self, *exc):
        return self._tx_stack.pop().__exit__(*exc)

    def close(self) -> None:
        self._raw.close()

