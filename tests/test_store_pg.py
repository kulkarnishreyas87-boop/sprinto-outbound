"""Store portability (SQLite <-> Postgres) and the web run-item / Hunter-cap helpers."""
import os
from datetime import datetime, timedelta, timezone

import httpx
import pytest

from sprinto.contacts import HunterClient, HunterError
from sprinto.models import DecisionRecord, Status
from sprinto.store import Store, _to_postgres


def test_placeholders_become_percent_s():
    assert _to_postgres("SELECT * FROM pages WHERE url=? AND domain=?") == \
        "SELECT * FROM pages WHERE url=%s AND domain=%s"


def test_insert_or_replace_becomes_upsert():
    sql = _to_postgres("INSERT OR REPLACE INTO hunter_cache(domain, response_json, fetched_at) VALUES (?,?,?)")
    assert sql == ("INSERT INTO hunter_cache(domain, response_json, fetched_at) VALUES (%s,%s,%s) "
                   "ON CONFLICT (domain) DO UPDATE SET response_json=EXCLUDED.response_json, "
                   "fetched_at=EXCLUDED.fetched_at")


def test_composite_key_upsert_and_identity():
    sql = _to_postgres("INSERT OR REPLACE INTO run_items(run_id, domain, state) VALUES (?,?,?)")
    assert "ON CONFLICT (run_id, domain) DO UPDATE SET state=EXCLUDED.state" in sql
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in _to_postgres(
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, x TEXT)")


def test_sqlite_is_default_without_database_url(tmp_path, monkeypatch):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    s = Store(tmp_path / "x.db")
    assert not s.is_postgres
    s.close()


# ---------- run items ----------

def test_run_items_claim_in_order_then_finish(store):
    store.add_run_items("r1", ["a.io", "b.io"], skipped=["old.io"])
    assert [(i["domain"], i["state"]) for i in store.run_items("r1")] == [
        ("a.io", "pending"), ("b.io", "pending"), ("old.io", "skipped")]
    assert store.active_run_id() == "r1"
    assert store.claim_next_item("r1") == "a.io"
    assert store.claim_next_item("r1") == "b.io"          # a.io is running, not pending
    store.finish_item("r1", "a.io", "rec-a")
    store.finish_item("r1", "b.io", "rec-b")
    assert store.claim_next_item("r1") is None and store.active_run_id() is None
    assert store.run_items("r1")[0]["record_id"] == "rec-a"


def test_stale_running_item_is_retried(store):
    store.add_run_items("r1", ["a.io"])
    store.claim_next_item("r1")
    old = (datetime.now(timezone.utc) - timedelta(minutes=10)).isoformat()
    store.conn.execute("UPDATE run_items SET updated_at=? WHERE run_id='r1'", (old,))
    store.conn.commit()
    assert store.reset_stale_items("r1") == 1 and store.claim_next_item("r1") == "a.io"


# ---------- Hunter monthly cap ----------

def test_hunter_cap_blocks_new_searches_but_not_cache(cfg, store):
    capped = cfg.contacts.model_copy(update={"hunter_monthly_cap": 2})
    calls = []
    client = httpx.Client(transport=httpx.MockTransport(
        lambda req: calls.append(req) or httpx.Response(200, json={"data": {"emails": []}})))
    h = HunterClient("k", store, capped, client=client)
    h.domain_search("a.io")
    h.domain_search("b.io")
    assert store.hunter_calls_since(30) == 2
    with pytest.raises(HunterError) as e:
        h.domain_search("c.io")
    assert e.value.reason_code == "hunter_monthly_cap" and len(calls) == 2
    assert h.domain_search("a.io") == ({"data": {"emails": []}}, False)     # cached: still fine


